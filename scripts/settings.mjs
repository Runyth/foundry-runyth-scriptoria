import {
  MODULE_ID,
  READER_MODES,
  SETTINGS
} from "./constants.mjs";
import { getReaderModeDescriptors } from "./document-views.mjs";
import { clearImporterLayout } from "./importer-layout.mjs";
import { localize } from "./i18n.mjs";
import { createEconomicsDefaultsApplicationClass } from "./economics-settings.mjs";
import { syncOpenWindows } from "./ui-look.mjs";

export function registerSettings() {
  globalThis.Hooks?.on?.("closeSettingsConfig", () => syncOpenWindows());

  game.settings.register(MODULE_ID, SETTINGS.stockFoundryLook, {
    name: localize(
      "RUNYTH-SCRIPTORIA.Settings.StockFoundryLook.Name",
      "Stock Foundry look"
    ),
    hint: localize(
      "RUNYTH-SCRIPTORIA.Settings.StockFoundryLook.Hint",
      "Keep the stock Foundry UI design for the windows of Runyth Scriptoria. By default they use the fleet-wide Garb & Grime look."
    ),
    scope: "client",
    config: true,
    type: Boolean,
    default: false
  });
  game.settings.register(MODULE_ID, SETTINGS.rootFolder, {
    name: localize("RUNYTH-SCRIPTORIA.Settings.RootFolder.Name", "Root Item folder"),
    hint: localize("RUNYTH-SCRIPTORIA.Settings.RootFolder.Hint", "The root Item Directory folder used for documents created by Runyth Scriptoria."),
    scope: "world",
    config: true,
    type: String,
    default: "Runyth Scriptoria"
  });

  game.settings.register(MODULE_ID, SETTINGS.createKindFolders, {
    name: localize("RUNYTH-SCRIPTORIA.Settings.CreateKindFolders.Name", "Create document-kind subfolders"),
    hint: localize("RUNYTH-SCRIPTORIA.Settings.CreateKindFolders.Hint", "Sort generated Items into type-specific folders."),
    scope: "world",
    config: true,
    type: Boolean,
    default: true
  });

  game.settings.register(MODULE_ID, SETTINGS.defaultAccess, {
    name: localize("RUNYTH-SCRIPTORIA.Settings.DefaultAccess.Name", "Default world Item access"),
    hint: localize("RUNYTH-SCRIPTORIA.Settings.DefaultAccess.Hint", "Choose whether a new world Item is hidden until held or placed, or immediately visible to all players."),
    scope: "world",
    config: true,
    type: String,
    choices: {
      embedded: localize("RUNYTH-SCRIPTORIA.Access.WhenHeldOrPlaced", "When held or placed"),
      observer: localize("RUNYTH-SCRIPTORIA.Access.AllPlayersImmediately", "All players immediately")
    },
    default: "embedded"
  });

  game.settings.register(MODULE_ID, SETTINGS.enableSceneDrop, {
    name: localize("RUNYTH-SCRIPTORIA.Settings.EnableSceneDrop.Name", "Create readable Journal notes on Scene drop"),
    hint: localize("RUNYTH-SCRIPTORIA.Settings.EnableSceneDrop.Hint", "Dropping a Runyth Scriptoria Item onto a Scene creates a Journal snapshot and Note at the drop position."),
    scope: "world",
    config: true,
    type: Boolean,
    default: true
  });

  game.settings.register(MODULE_ID, SETTINGS.scenePlayerAccess, {
    name: localize("RUNYTH-SCRIPTORIA.Settings.ScenePlayerAccess.Name", "Scene Journal player access"),
    hint: localize("RUNYTH-SCRIPTORIA.Settings.ScenePlayerAccess.Hint", "Control whether all players can open Journals generated by dropping Runyth Scriptoria Items onto Scenes."),
    scope: "world",
    config: true,
    type: String,
    choices: {
      observer: localize("RUNYTH-SCRIPTORIA.Access.AllPlayersCanRead", "All players can read"),
      embedded: localize("RUNYTH-SCRIPTORIA.Access.GameMasterOnly", "Game Master only")
    },
    default: "observer"
  });

  game.settings.register(MODULE_ID, SETTINGS.defaultSceneDocumentView, {
    name: localize(
      "RUNYTH-SCRIPTORIA.Settings.DefaultSceneDocumentView.Name",
      "Default view for scene documents"
    ),
    hint: localize(
      "RUNYTH-SCRIPTORIA.Settings.DefaultSceneDocumentView.Hint",
      "Choose which reader opens by default when a Runyth Scriptoria document is opened from a scene."
    ),
    scope: "world",
    config: true,
    restricted: true,
    type: String,
    choices: Object.fromEntries(
      getReaderModeDescriptors().map((mode) => [mode.id, mode.label])
    ),
    default: READER_MODES.simpleReader
  });

  game.settings.register(MODULE_ID, SETTINGS.itemEconomicsOverrides, {
    name: localize(
      "RUNYTH-SCRIPTORIA.Economics.SettingsStorage.Name",
      "Item economics overrides"
    ),
    hint: localize(
      "RUNYTH-SCRIPTORIA.Economics.SettingsStorage.Hint",
      "Internal world storage for Runyth Scriptoria type price and weight overrides."
    ),
    scope: "world",
    config: false,
    restricted: true,
    type: Object,
    default: {}
  });

  game.settings.registerMenu(MODULE_ID, SETTINGS.itemEconomicsDefaultsMenu, {
    name: localize(
      "RUNYTH-SCRIPTORIA.Economics.SettingsMenu.Name",
      "Item Price and Weight Defaults"
    ),
    label: localize(
      "RUNYTH-SCRIPTORIA.Economics.SettingsMenu.Label",
      "Configure Price and Weight Defaults"
    ),
    hint: localize(
      "RUNYTH-SCRIPTORIA.Economics.SettingsMenu.Description",
      "Configure world defaults for every currently known Runyth Scriptoria type."
    ),
    icon: "fa-solid fa-coins",
    type: createEconomicsDefaultsApplicationClass(),
    restricted: true
  });

  game.settings.register(MODULE_ID, SETTINGS.debugLogging, {
    name: localize(
      "RUNYTH-SCRIPTORIA.Settings.DebugLogging.Name",
      "Enable Runyth Scriptoria debug logging"
    ),
    hint: localize(
      "RUNYTH-SCRIPTORIA.Settings.DebugLogging.Hint",
      "Write focused Runyth Scriptoria diagnostics to the browser console without logging imported document content."
    ),
    scope: "client",
    config: true,
    restricted: true,
    type: Boolean,
    default: false
  });

  game.settings.register(MODULE_ID, SETTINGS.openAfterCreate, {
    name: localize("RUNYTH-SCRIPTORIA.Settings.OpenAfterCreate.Name", "Open reader after creation"),
    hint: localize("RUNYTH-SCRIPTORIA.Settings.OpenAfterCreate.Hint", "Immediately display the reading view after a new Runyth Scriptoria Item is created."),
    scope: "client",
    config: true,
    type: Boolean,
    default: true
  });

  game.settings.register(MODULE_ID, SETTINGS.rememberImporterWindow, {
    name: localize("RUNYTH-SCRIPTORIA.Settings.RememberImporterWindow.Name", "Remember importer window position and size"),
    hint: localize("RUNYTH-SCRIPTORIA.Settings.RememberImporterWindow.Hint", "Restore the Markdown/HTML importer window's last size and placement separately in this browser."),
    scope: "client",
    config: true,
    type: Boolean,
    default: true
  });

  game.settings.register(MODULE_ID, SETTINGS.importerWindowLayout, {
    name: localize("RUNYTH-SCRIPTORIA.Settings.ImporterWindowLayout.Name", "Importer window layout"),
    hint: localize("RUNYTH-SCRIPTORIA.Settings.ImporterWindowLayout.Hint", "Internal client-specific storage for the importer window's validated dimensions and coordinates."),
    scope: "client",
    config: false,
    type: String,
    default: ""
  });

  game.settings.registerMenu(MODULE_ID, SETTINGS.resetImporterWindow, {
    name: localize("RUNYTH-SCRIPTORIA.Settings.ResetImporterWindow.Name", "Reset importer window position and size"),
    label: localize("RUNYTH-SCRIPTORIA.Settings.ResetImporterWindow.Label", "Reset importer window"),
    hint: localize("RUNYTH-SCRIPTORIA.Settings.ResetImporterWindow.Hint", "Clear the layout remembered by this browser. The next importer opens at its default centered placement."),
    icon: "fa-solid fa-window-restore",
    type: createResetImporterWindowDialogClass(),
    restricted: false
  });
}

function createResetImporterWindowDialogClass() {
  return class ResetImporterWindowDialog extends foundry.applications.api.DialogV2 {
    constructor() {
      super({
        window: {
          title: localize("RUNYTH-SCRIPTORIA.Settings.ResetImporterWindow.DialogTitle", "Reset Runyth Scriptoria Importer Window"),
          icon: "fa-solid fa-window-restore"
        },
        content: `
          <p>${localize("RUNYTH-SCRIPTORIA.Settings.ResetImporterWindow.Confirm", "Clear the importer window position and size remembered by this browser?")}</p>
          <p class="notes">${localize("RUNYTH-SCRIPTORIA.Settings.ResetImporterWindow.Note", "The next importer window will use Runyth Scriptoria's default dimensions and centered placement.")}</p>
        `,
        buttons: [
          {
            action: "reset",
            label: localize("RUNYTH-SCRIPTORIA.Settings.ResetImporterWindow.Action", "Reset Window Layout"),
            icon: "fa-solid fa-window-restore",
            default: true,
            callback: async () => {
              await clearImporterLayout();
              ui.notifications.info(localize("RUNYTH-SCRIPTORIA.Settings.ResetImporterWindow.Success", "Runyth Scriptoria importer window position and size reset."));
              return true;
            }
          },
          {
            action: "cancel",
            label: localize("RUNYTH-SCRIPTORIA.Actions.Cancel", "Cancel"),
            icon: "fa-solid fa-xmark"
          }
        ]
      });
    }
  };
}
